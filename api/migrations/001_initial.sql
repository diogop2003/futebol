CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(160) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('admin','manager') NOT NULL DEFAULT 'manager',
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS people (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(160) NOT NULL,
 name_key VARCHAR(190) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL UNIQUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 kind ENUM('monthly','daily','barbecue') NOT NULL,
 reference_date DATE NOT NULL,
 title VARCHAR(160) NOT NULL DEFAULT '',
 amount DECIMAL(11,2) NOT NULL CHECK(amount >= 0),
 monthly_key DATE GENERATED ALWAYS AS (CASE WHEN kind = 'monthly' AND deleted_at IS NULL THEN reference_date ELSE NULL END) PERSISTENT,
 active_key VARCHAR(230) GENERATED ALWAYS AS (CASE WHEN deleted_at IS NULL THEN CONCAT(kind, ':', reference_date, ':', title) ELSE NULL END) PERSISTENT,
 request_key CHAR(36) NOT NULL UNIQUE,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_by BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 deleted_at DATETIME NULL,
 UNIQUE KEY uq_monthly(monthly_key),
 UNIQUE KEY uq_event(active_key),
 KEY idx_event_period(kind, reference_date, deleted_at),
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE RESTRICT,
 CHECK(kind <> 'monthly' OR DAY(reference_date) = 1)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS event_participants (
 event_id BIGINT UNSIGNED NOT NULL,
 person_id BIGINT UNSIGNED NOT NULL,
 amount DECIMAL(11,2) NOT NULL CHECK(amount >= 0),
 paid BOOLEAN NOT NULL DEFAULT FALSE,
 paid_at DATE NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(event_id, person_id),
 FOREIGN KEY(event_id) REFERENCES events(id) ON DELETE RESTRICT,
 FOREIGN KEY(person_id) REFERENCES people(id) ON DELETE RESTRICT,
 CHECK(paid = TRUE OR paid_at IS NULL)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS expenses (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 expense_date DATE NULL,
 reference_date DATE NOT NULL,
 amount DECIMAL(11,2) NOT NULL CHECK(amount > 0),
 category ENUM('field','goalkeepers','barbecue','additional') NOT NULL,
 description VARCHAR(1000) NOT NULL DEFAULT '',
 request_key CHAR(36) NOT NULL UNIQUE,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_by BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 deleted_at DATETIME NULL,
 KEY idx_expense_period(reference_date, deleted_at),
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE RESTRICT,
 CHECK(DAY(reference_date) = 1)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS login_attempts (
 bucket CHAR(64) PRIMARY KEY,
 attempts INT UNSIGNED NOT NULL DEFAULT 0,
 window_start DATETIME NOT NULL,
 KEY idx_attempt_window(window_start)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 action VARCHAR(40) NOT NULL,
 entity VARCHAR(40) NOT NULL,
 entity_id BIGINT UNSIGNED NOT NULL,
 before_data LONGTEXT NULL,
 after_data LONGTEXT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT,
 KEY idx_audit_entity(entity, entity_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS financial_config (
 id TINYINT UNSIGNED PRIMARY KEY CHECK(id = 1),
 basis ENUM('reference') NOT NULL,
 opening_date DATE NOT NULL,
 opening_balance DECIMAL(11,2) NOT NULL,
 description VARCHAR(1000) NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE RESTRICT,
 CHECK(DAY(opening_date) = 1)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS legacy_imports (
 source_key VARCHAR(100) PRIMARY KEY,
 source_hash CHAR(64) NOT NULL,
 event_id BIGINT UNSIGNED NULL,
 expense_id BIGINT UNSIGNED NULL,
 imported_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(event_id) REFERENCES events(id) ON DELETE RESTRICT,
 FOREIGN KEY(expense_id) REFERENCES expenses(id) ON DELETE RESTRICT
) ENGINE=InnoDB;
